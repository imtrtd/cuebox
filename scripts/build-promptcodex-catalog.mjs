// Regenerates src/lib/promptcodex-catalog.ts from the PromptCodex export in
// data/. Run with `npm run build:catalog` after replacing the export.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(root, "data", "promptcodex-library.json");
const target = path.join(root, "src", "lib", "promptcodex-catalog.ts");

const MIN_BODY_LENGTH = 40;
const CYRILLIC = /[а-яё]/i;

const library = JSON.parse(readFileSync(source, "utf8"));

const usable = (library.prompts ?? []).filter((prompt) => {
  const body = prompt.variants?.[0]?.body ?? "";
  return body.trim().length >= MIN_BODY_LENGTH;
});

// The export carries English and Russian editions of some prompts with a
// byte-identical body. The app is Russian, so keep the Russian title.
const byBody = new Map();
for (const prompt of usable) {
  const body = prompt.variants[0].body;
  const current = byBody.get(body);
  if (!current) {
    byBody.set(body, prompt);
    continue;
  }
  const currentIsRussian = CYRILLIC.test(current.title ?? "");
  const nextIsRussian = CYRILLIC.test(prompt.title ?? "");
  if (nextIsRussian && !currentIsRussian) byBody.set(body, prompt);
}

const curated = [...byBody.values()]
  .map((prompt) => ({
    id: prompt.id,
    title: prompt.title,
    description: prompt.description ?? "",
    categoryId: prompt.categoryId ?? "",
    categoryName: prompt.categoryName ?? "",
    isFavorite: Boolean(prompt.isFavorite),
    isPinned: Boolean(prompt.isPinned),
    tags: [...(prompt.tags ?? [])].sort(),
    createdDate: prompt.createdDate,
    modifiedDate: prompt.modifiedDate,
    variables: (prompt.variables ?? [])
      .slice()
      .sort((a, b) => (a.displayOrder ?? 0) - (b.displayOrder ?? 0))
      .map((variable) => ({
        name: variable.name,
        description: variable.description ?? "",
        displayOrder: variable.displayOrder ?? 0,
        optionsValue: variable.optionsValue ?? "",
        typeRawValue: variable.typeRawValue ?? "string",
      })),
    variants: (prompt.variants ?? [])
      .slice()
      .sort((a, b) => (a.displayOrder ?? 0) - (b.displayOrder ?? 0))
      .map((variant) => ({
        id: variant.id,
        body: variant.body,
        displayOrder: variant.displayOrder ?? 0,
      })),
  }))
  .sort((a, b) => a.title.localeCompare(b.title, "ru"));

const meta = {
  exportDate: library.exportDate ?? null,
  folders: (library.folders ?? []).map(({ id, name, displayOrder }) => ({ id, name, displayOrder: displayOrder ?? 0 })),
  globalVariables: (library.globalVariables ?? []).map(({ name, description, defaultValue, typeRawValue }) => ({
    name, description: description ?? "", defaultValue: defaultValue ?? "", typeRawValue: typeRawValue ?? "string",
  })),
  projects: (library.projects ?? []).map((p) => ({
    id: p.id, name: p.name, description: p.projectDescription ?? "", type: p.projectTypeRawValue ?? "",
    status: p.statusRawValue ?? "", repositoryURL: p.repositoryURL ?? "", websiteURL: p.websiteURL ?? "",
    startDate: p.startDate ?? null, targetDate: p.targetDate ?? null,
    heroImageUrl: p.heroImageUrl ?? null, iconImageUrl: p.iconImageUrl ?? null,
  })),
  services: (library.services ?? []).map((s) => ({
    id: s.id, name: s.name, isBuiltIn: Boolean(s.isBuiltIn), iconUrl: s.customIconUrl ?? null,
  })),
  tagCount: (library.tags ?? []).length,
  promptCount: (library.prompts ?? []).length,
};

const skipped = (library.prompts ?? []).length - curated.length;

const file = `// Generated by scripts/build-promptcodex-catalog.mjs — do not edit by hand.
// Source: data/promptcodex-library.json (PromptCodex export ${library.exportDate}).
import type { PromptCodexPrompt } from "./promptcodex";

export const PROMPTCODEX_CATALOG: PromptCodexPrompt[] = ${JSON.stringify(curated, null, 2)};

/** Library-level metadata from the same export (images live in public/library). */
export const PROMPTCODEX_LIBRARY_META = ${JSON.stringify(meta, null, 2)} as const;
`;

writeFileSync(target, file);
console.log(
  `Wrote ${curated.length} prompts to ${path.relative(root, target)} (skipped ${skipped}).`,
);
